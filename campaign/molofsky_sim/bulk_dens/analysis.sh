#!/bin/sh
# Regenerates bulk_dens/analysis.md (all tables of NOTES.md Sec. 9) and dens.png from the raw runs.
# Run from campaign/molofsky_sim:  sh bulk_dens/analysis.sh
cd "$(dirname "$0")/.." || exit 1
{
echo "# Sec. 9 analysis tables (generated by bulk_dens/analysis.sh on $(date '+%d %b %Y %H:%M'); mdens.py on the raw runs in bulk_dens/)"
echo
echo "## Cost"; echo; echo '```'; python3 bulk_dens/cost.py; echo '```'; echo
echo "## Runs"; echo; python3 mdens.py runs; echo
echo "## Points, last half of each run (the protocol; -> bulk_dens/points.txt)"; echo; python3 mdens.py points; echo
echo "## Points, window 1.5e5-3e5"; echo; python3 mdens.py points 1.5e5,3e5; echo
echo "## Points, window 3e5-6e5"; echo; python3 mdens.py points 3e5,6e5; echo
echo "## Points, window 6e5-1.2e6"; echo; python3 mdens.py points 6e5,1.2e6; echo
echo "## Blocks of 1e5 steps, runs within 0.5e-4 of the reversal"; echo; python3 mdens.py blocks 0.5e-4; echo
echo "## Fits, stationary last-half points (bulk_dens/points.txt)"; echo; python3 mdens.py fit; echo
echo "## Fits, all last-half points including split/drifting ones (--all)"; echo; python3 mdens.py fit bulk_dens/points.txt --all; echo
echo "## Fits, stationary points plus the 0.4e-4 point as 0.177 +- 0.004 (bulk_dens/points_edgevar.txt)"; echo; python3 mdens.py fit bulk_dens/points_edgevar.txt; echo
echo "## Slopes (steepening check), stationary last-half points"; echo; python3 mdens.py slopes; echo
} > bulk_dens/analysis.md 2>&1
python3 plot_dens.py dens.png
echo "wrote bulk_dens/analysis.md ($(wc -l < bulk_dens/analysis.md) lines) and dens.png"
