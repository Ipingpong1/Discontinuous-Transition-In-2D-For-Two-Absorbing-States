"""Fig. voter: near the voter point. (a) chi_L = L^2 <m^2> against L (E6/E7); (b) seed survival
t P_s(t) (E8a, E8a_long); (c) width of the active layer on a wall between the absorbing phases (E8b)."""
import csv
import glob
import json
import os
import re

import matplotlib.pyplot as plt
from matplotlib.ticker import NullFormatter, NullLocator
import numpy as np

from common import FIGDATA, PAGE, ROOT, RUNS, label, save
import spread

fig, axs = plt.subplots(1, 3, figsize=(PAGE, 2.9), gridspec_kw=dict(wspace=0.32))

fig.subplots_adjust(top=.72, bottom=.15)

# (a) Unconditioned, time-weighted independent-run estimates. The CSV is
# generated by campaign.v2.analysis.susceptibility; no hand-entered values.
summary_path = os.path.join(ROOT, "campaign/v2/results/susceptibility/summary.csv")
with open(summary_path) as stream:
    chi_rows = [r for r in csv.DictReader(stream)
                if r["window"] == "planned" and r["estimator"] == "all"]
curves = [(0.9, .012257, "o", "C2"),
          (0.98, .0025704, "o", "C0"), (0.98, .003024, "^", "C0"),
          (0.99, .0012827, "v", "C3"), (0.99, .0012954, "o", "C3"),
          (0.99, .0013335, "s", "C3"), (0.99, .001524, "^", "C3")]
ax = axs[0]
for p, q, marker, color in curves:
    rows = sorted([r for r in chi_rows if abs(float(r["p"])-p)<1e-10
                   and abs(float(r["q"])-q)<1e-12], key=lambda r:int(r["Lx"]))
    L = np.array([int(r["Lx"]) for r in rows])
    c = np.array([float(r["chi"]) for r in rows])
    lo = np.array([float(r["chi_ci_low"]) for r in rows])
    hi = np.array([float(r["chi_ci_high"]) for r in rows])
    ax.errorbar(L,c,yerr=np.maximum(np.vstack([c-lo,hi-c]),0),fmt=marker+"-",
                color=color,ms=3,capsize=1.2,lw=.8,
                label=f"${p:g}$, ${q:g}$")
Lg=np.array([1500,4500])
ax.plot(Lg,8e4*(Lg/1500)**1.75,"k--",lw=.8)
ax.text(3400,6.5e5,r"$L^{7/4}$",fontsize=7,ha="center",va="bottom")
ax.legend(title=r"$p$, $q$ (actual)",title_fontsize=5.5,fontsize=4.8,
          loc="lower left",bbox_to_anchor=(0,1.01),ncol=2,
          handlelength=1.0,columnspacing=.6,labelspacing=.18,handletextpad=.3,borderaxespad=0)
ax.set(xscale="log",yscale="log",xlabel=r"$L$",ylabel=r"$\chi_L=L^2\langle m^2\rangle$",
       ylim=(800,3e6),xlim=(400,5500))
ax.set_xticks([512,1024,2048,4096],["512","1024","2048","4096"])
ax.xaxis.set_minor_locator(NullLocator())
ax.xaxis.set_minor_formatter(NullFormatter())
ax.text(.97,.97,"all runs; 95% intervals",transform=ax.transAxes,fontsize=5.2,color=".35",ha="right",va="top")
label(ax,"(a)",x=.88,y=.08)

# (b) seeds: t P_s(t) for a 2x2 live block in the dead state
ax = axs[1]

# The targeted p=.99 tail is analyzed from integer survivor counts. Use the new
# confirmatory campaign only after all sixteen fixed-N shards finish; a subset of
# wall-clock-completed shards can select against expensive long trajectories.
tail_dir = os.path.join(ROOT, "campaign", "v2", "results", "seed_tails")
tail_rows, tail_population = [], None
if os.path.exists(os.path.join(tail_dir, "summary.json")):
    with open(os.path.join(tail_dir, "summary.json")) as stream:
        tail_summary = json.load(stream)
    tail_population = "confirmatory_8M" if tail_summary.get("confirmatory_campaign_complete",False) else "legacy_3M"
    with open(os.path.join(tail_dir, "survival.csv")) as stream:
        tail_rows = [r for r in csv.DictReader(stream) if r["population"] == tail_population]


def pooled(pattern):
    files = sorted(glob.glob(os.path.join(RUNS, pattern)))
    t, data, meta = spread.load(files if len(files) > 1 else files[0])
    S = data.sum(0)
    return t, S[:, 1] / S[:, 0]


t, ps = pooled("E8a_spread/out/p1_a0.5_j2_q0_L2048_seed.txt")
ok = t >= 10
ax.plot(t[ok], (t * ps)[ok], "k-", lw=1.4, label="voter")
pts = [(0.98, .0025704, "C0", "-"), (0.98, .002646, "C0", "--"),
       (0.99, .0012954, "C3", "-"), (0.99, .0013335, "C3", "--"),
       (0.995, .0006324, "C1", "-"), (0.995, .000651, "C1", "--")]
for p, q, c, ls in pts:
    pat = f"E8a_long/out/p{p}_a0.5_j2_q{q:.7f}".rstrip("0") + "_L8192_T*_k*.txt"
    files = sorted(glob.glob(os.path.join(RUNS, pat)))
    if not files:
        print("missing", pat)
        continue
    t, data, meta = spread.load(files)
    S = data.sum(0)
    P = S[:, 1] / S[:, 0]
    count_label = ""
    if p == 0.99 and abs(q - 0.0012954) < 1e-12 and tail_rows:
        t = np.array([float(r["time"]) for r in tail_rows])
        P = np.array([float(r["survival"]) for r in tail_rows])
        low = np.array([float(r["ci_low"]) for r in tail_rows])
        high = np.array([float(r["ci_high"]) for r in tail_rows])
        tail = (t >= 1e4) & (high > 0)
        ax.fill_between(t[tail], (t * low)[tail], (t * high)[tail], color=c, alpha=0.13, lw=0)
        count_label = f", ${int(tail_rows[-1]['n']) / 1e6:g}\\mathrm{{M}}$"
    ok = (t >= 10) & (P > 0)
    ax.plot(t[ok], (t * P)[ok], ls, color=c, label=f"$p={p}$, $q={q:g}$" + count_label)
ax.set(xscale="log", yscale="log", xlabel=r"$t$", ylabel=r"$t\,P_s(t)$", xlim=(10, 1.2e6), ylim=(0.5, 300))
ax.legend(fontsize=4.8, loc="lower left", bbox_to_anchor=(0,1.01), ncol=2,
          handlelength=1.2, columnspacing=.6, labelspacing=.18, handletextpad=.3, borderaxespad=0)
ax.text(0.03, 0.035, "finite time; black and dashed:\nadaptive stopping", transform=ax.transAxes, fontsize=5.6, color="0.3")
label(ax, "(b)", x=0.88, y=0.95)

# (c) walls: width W(t) of the active layer (E8b; wall.py W, mean over the two walls and 2 seeds)
ax = axs[2]
wall_pairs = {0.9: (.011662,.012495), 0.98: (.0024696,.002646),
              0.99: (.0012446,.0013335), 0.995: (.0006076,.000651)}
pc = {0.9: "C2", 0.98: "C0", 0.99: "C3", 0.995: "C1"}
for p, (qlow,qhigh) in wall_pairs.items():
    for q, ls in ((qlow, "-"), (qhigh, "--")):
        files = sorted(glob.glob(os.path.join(FIGDATA, "E8b_wall", f"p{p}_a0.5_j2_q{q:.7f}".rstrip("0")
                                              + "_Lx1024_Ly4096_s?.csv")))
        if not files:
            print("missing wall", p, q)
            continue
        runs = [np.array([[float(v) for v in r] for r in list(csv.reader(open(f)))[1:]]) for f in files]
        tt = runs[0][:, 0]
        W = np.mean([r[:, 6] for r in runs], axis=0)
        ok = tt >= 100
        ax.plot(tt[ok], W[ok], ls, color=pc[p], label=f"$p={p}$" if ls == "-" else None)
ref = sorted(glob.glob(os.path.join(FIGDATA, "E16_wall_ref", "p1_a0.5_j2_q0_Lx1024_Ly4096_s?.csv")))
if ref:
    runs = [np.array([[float(v) for v in r] for r in list(csv.reader(open(f)))[1:]]) for f in ref]
    tt = runs[0][:, 0]
    W = np.mean([r[:, 6] for r in runs], axis=0)
    ok = tt >= 100
    ax.plot(tt[ok], W[ok], "k-", lw=1.4, label="voter")
ax.set(xscale="log", yscale="log", xlabel=r"$t$", ylabel=r"layer width $W$", xlim=(100, 1.2e6), ylim=(8, 2500))
ax.legend(fontsize=5.5, loc="upper left", bbox_to_anchor=(0.0, 0.9))
ax.text(0.97, 0.05, "solid: lower q; dashed: higher q", transform=ax.transAxes, ha="right", fontsize=5.5)
label(ax, "(c)", x=0.04, y=0.97)
save(fig, "fig_voter")
